#Requires -Version 5.1
[CmdletBinding()]
param([switch]$Check)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$version = [IO.File]::ReadAllText((Join-Path $root 'version.txt')).Trim()
if ($version -notmatch '^\d+\.\d+\.\d+$') { throw 'version.txt must contain a numeric major.minor.patch version.' }
$encoding = New-Object Text.UTF8Encoding($false)
$generated = "// Generated by packaging/sync_version.ps1 from version.txt. Do not edit.`nnamespace TokLens`n{`n    internal static class BuildVersion`n    {`n        internal const string Version = `"$version`";`n        internal const string AssemblyVersion = `"$version.0`";`n    }`n}`n"
$source = Join-Path $root 'src\BuildVersion.generated.cs'
$manifestPath = Join-Path $root 'src\app.manifest'
$manifest = [IO.File]::ReadAllText($manifestPath)
$identityPattern = '<assemblyIdentity\b[^>]*\bname="TokLens\.App"[^>]*>'
if ([regex]::Matches($manifest, $identityPattern).Count -ne 1) { throw 'app.manifest must contain exactly one TokLens.App assemblyIdentity.' }
$manifestNew = [regex]::Replace($manifest, $identityPattern, {
    param($match)
    if (-not [regex]::IsMatch($match.Value, '\bversion="[^"]+"')) { throw 'TokLens.App assemblyIdentity requires a version attribute.' }
    [regex]::Replace($match.Value, '\bversion="[^"]+"', ('version="' + $version + '.0"'))
})
$agentPath = Join-Path $root 'vps\toklens_agent.py'
$agent = [IO.File]::ReadAllText($agentPath)
$pricing = Get-Content -LiteralPath (Join-Path $root 'pricing\service_tier_prices.json') -Raw -Encoding UTF8 | ConvertFrom-Json
$pricingJson = ConvertTo-Json -InputObject @($pricing) -Depth 20 -Compress
# JSON is parsed at runtime rather than assuming JSON booleans/null are Python literals.
$agentNew = [regex]::Replace($agent, '(?m)^AGENT_VERSION = "[^"]+"', ('AGENT_VERSION = "' + $version + '"'))
$agentNew = [regex]::Replace($agentNew, '(?m)^BUNDLED_TIER_PRICES = .*$', { param($match) "BUNDLED_TIER_PRICES = json.loads(r'''$pricingJson''')  # Generated from pricing/service_tier_prices.json." })
if ($Check) {
    if (-not (Test-Path -LiteralPath $source) -or [IO.File]::ReadAllText($source).Replace("`r`n", "`n") -cne $generated) { throw 'Generated C# version is stale. Run packaging/sync_version.ps1.' }
    if ($agentNew -cne $agent) { throw 'Python version or bundled pricing is stale. Run packaging/sync_version.ps1.' }
    if ($manifestNew -cne $manifest) { throw 'Windows manifest version is stale. Run packaging/sync_version.ps1.' }
} else {
    [IO.File]::WriteAllText($source, $generated, $encoding)
    if ($agentNew -cne $agent) { [IO.File]::WriteAllText($agentPath, $agentNew, $encoding) }
    if ($manifestNew -cne $manifest) { [IO.File]::WriteAllText($manifestPath, $manifestNew, $encoding) }
}
Write-Host "Version and pricing source verified: $version"
